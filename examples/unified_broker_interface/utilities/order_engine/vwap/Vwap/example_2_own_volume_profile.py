"""Uses a caller's own measured volume profile for a VWAP order, shows the edges of the day, and the profiles it refuses.

Somebody who has measured their instrument's volume passes `volume_profile`, a list of relative weights for consecutive half hours from the 09:15 open, and `read_profile` uses it instead of the default shape. A half hour past the end of the list takes the list's last weight.

This program gives a four-weight profile to a buy of 1,000 ITC in four slices starting at 09:15 on Thursday 1 October 2026 and prints the slice sizes. It also shows `bucket_of` at the edges of the day: a moment before the open counts as the first half hour, and one after the close as whichever half hour it falls in, so an order running past the bell is weighted by the nearest part of the day rather than refused.

Last, `read_profile` refuses three profiles with HTTP 400: an empty list, a negative weight, and weights that add up to nothing. The program builds its runners without running them, and writes the schedule's start into the parent's parameters itself, so the output does not depend on when it is run. The placement is a stand-in; nothing is sent. The event log is the `RecordingEventLog` stand-in and the parent store keeps nothing, so nothing leaves the machine.

Run it from the project root:

    python examples/unified_broker_interface/utilities/order_engine/vwap/Vwap/example_2_own_volume_profile.py
"""

